/**
 * Construct project file URL based on environment
 */
export function getProjectFileUrl(projectName: string, type: string, fileName: string): string {
  const relativePath = `./project-files/${projectName}/${type}/${fileName}`;
  
  if (isDevelopment()) {
    // In development, use full localhost URL
    return `http://localhost:5180${relativePath}`;
  } else {
    // In production (Electron app), use safe-file protocol
    // This will be handled by Electron's custom protocol handler
    const sanitizedProjectName = projectName.replace(/[<>:"/\\|?*]/g, '_').trim();
    
    // Use secure path construction without process.cwd or process.env
    // The actual file loading should use getProjectFileAsDataUrl for security
    const projectsDir = `Documents/Docfai Projects`; // Relative to user home
    const filePath = `${projectsDir}/${sanitizedProjectName}/${type}/${fileName}`;
    return `safe-file://${filePath.replace(/\\/g, '/')}`;
  }
}

/**
 * Securely get project file as data URL using IPC
 * This is the recommended method for loading project files in production
 */
export async function getProjectFileAsDataUrl(projectName: string, type: string, fileName: string): Promise<string | null> {
  if (typeof window === 'undefined' || !window.electronAPI) {
    console.warn('electronAPI not available');
    return null;
  }

  try {
    // Strip query parameters from fileName (cache busters like ?t=timestamp)
    const cleanFileName = fileName.split('?')[0];
    let absolutePath: string | null = null;

    // Handle different file types
    if (type === 'screenshots' || type === 'step_by_step_screenshots') {
      // Extract just the filename if a path was passed
      const actualFileName = cleanFileName.includes('/') || cleanFileName.includes('\\') ? cleanFileName.split(/[\/\\]/).pop() || cleanFileName : cleanFileName;

      // Use the specific screenshot method for screenshots
      absolutePath = await window.electronAPI.getAbsoluteScreenshotPath(projectName, actualFileName);
    } else {
      // For other types (like diagrams), use the general project file path IPC handler
      const relativePath = `${type}/${cleanFileName}`;
      try {
        absolutePath = await window.electronAPI.ipcInvoke('get-project-file-path', projectName, relativePath);
      } catch (error) {
        console.warn(`Failed to get project file path for ${relativePath}:`, error);
        absolutePath = null;
      }
    }

    if (!absolutePath) {
      console.warn(`[getProjectFileAsDataUrl] File not found: ${fileName} in project ${projectName}`);
      return null;
    }

    // Convert to data URL using secure IPC method
    const dataUrl = await window.electronAPI.getFileUrl(absolutePath);
    return dataUrl;
  } catch (error) {
    console.error('[getProjectFileAsDataUrl] Error:', error);
    return null;
  }
}
